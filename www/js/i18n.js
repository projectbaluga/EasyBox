let currentLanguage = localStorage.getItem('eb_language') || 'en';

function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLanguage = lang;
    localStorage.setItem('eb_language', lang);
    applyTranslations();
}

function t(key) {
    if (!translations[currentLanguage]) return key;
    return translations[currentLanguage][key] || key;
}

function applyTranslations() {
    // 1. First handle standard [data-i18n]
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const translation = t(key);

        if (el.tagName === 'INPUT' && (el.type === 'button' || el.type === 'submit')) {
            el.value = translation;
        } else {
            // Check if translation contains HTML tags
            const hasHtml = /<[a-z][\s\S]*>/i.test(translation);

            if (hasHtml) {
                // For HTML translations, we might need to preserve icons if they exist
                const icon = el.querySelector('svg');
                if (icon) {
                    el.innerHTML = '';
                    el.appendChild(icon);
                    el.insertAdjacentHTML('beforeend', ' ' + translation);
                } else {
                    el.innerHTML = translation;
                }
            } else {
                // Handle elements with children (like icons or hints)
                // We look for the first non-empty text node
                let textNode = Array.from(el.childNodes).find(node => node.nodeType === 3 && node.nodeValue.trim() !== '');

                if (textNode) {
                    // Preserve leading/trailing whitespace if any
                    const leadingSpace = textNode.nodeValue.match(/^\s*/)[0];
                    const trailingSpace = textNode.nodeValue.match(/\s*$/)[0];
                    textNode.nodeValue = leadingSpace + translation + trailingSpace;
                } else if (el.childNodes.length === 0) {
                    el.textContent = translation;
                } else if (el.childNodes.length === 1 && el.firstChild.nodeType === 3) {
                    el.firstChild.nodeValue = translation;
                }
            }
        }
    });

    // 2. Separately handle [data-i18n-placeholder]
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.setAttribute('placeholder', t(key));
    });
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
});
